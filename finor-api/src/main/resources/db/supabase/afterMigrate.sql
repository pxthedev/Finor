-- Only loaded by the supabase profile; the Java API owns access to this schema.
REVOKE ALL ON SCHEMA finor FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA finor FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA finor FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA finor REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA finor REVOKE ALL ON SEQUENCES FROM PUBLIC;
DO $$
DECLARE api_role TEXT;
BEGIN
  FOREACH api_role IN ARRAY ARRAY['anon','authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname=api_role) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA finor FROM %I',api_role);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA finor FROM %I',api_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA finor FROM %I',api_role);
      EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA finor REVOKE ALL ON TABLES FROM %I',api_role);
      EXECUTE format('ALTER DEFAULT PRIVILEGES IN SCHEMA finor REVOKE ALL ON SEQUENCES FROM %I',api_role);
    END IF;
  END LOOP;
END $$;
